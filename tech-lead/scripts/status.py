"""Project status: derives initiative state from files, renders STATUS.md and a session brief.

Run from a SessionStart hook with --brief, so --brief must never raise or break a session.
"""
from __future__ import annotations

import datetime
import os
import re
import subprocess
import sys
from pathlib import Path

HEADER = "<!-- generated by tech-lead status.py, do not edit -->"
INSTRUCTION = (
    "Propose next steps to the user as a short list based on this status, "
    "and wait for their choice before starting work. If you are already carrying out "
    "an approved tech-lead plan or autopilot in this session, continue it instead."
)
BRIEF_MAX_LINES = 25
BRIEF_BACKLOG = 5
RECENT = 5
OPEN_PREFIX = "- [ ] "
CODEMAP_MIN_FILES = 30
CODEMAP_UPDATE_MIN = 16
CODEMAP_REBUILD_MIN = 51
CODEMAP_STALE_DAYS = 30
CODEMAP_STALE_COMMITS = 20

# (state, section heading) in display order
SECTIONS = (
    ("in progress", "In progress"),
    ("planned", "Planned"),
    ("specified", "Specified"),
    ("proposed", "Proposed"),
    ("unknown (ledger error)", "Unknown"),
)
BRIEF_STATES = ("in progress", "planned", "specified")


def _core():
    import ledger_core
    return ledger_core


def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def initiative_state(folder: Path) -> dict:
    folder = Path(folder)
    m = re.match(r"\d{4}-\d{2}-\d{2}", folder.name)
    info = {
        "name": folder.name,
        "path": os.path.abspath(str(folder)),
        "date": m.group(0) if m else "",
        "state": "proposed",
        "waves_done": 0,
        "waves_total": 0,
        "next_wave": None,
    }

    closed = any(line.startswith("Closed:")
                 for line in _read_text(folder / "journal.md").splitlines())

    ledger = None
    ledger_error = False
    ledger_path = folder / "ledger.json"
    if ledger_path.exists():
        try:
            core = _core()
            data = core.load(str(ledger_path))
            if core.validate(data):
                ledger_error = True
            else:
                ledger = data
        except Exception:
            ledger_error = True

    done_ids: set = set()
    if ledger is not None:
        core = _core()
        tasks = ledger.get("tasks", [])
        done_ids = set(ledger.get("done", []))
        wave_of = core.waves(tasks)
        by_wave: dict = {}
        for t in tasks:
            by_wave.setdefault(wave_of[t["id"]], []).append(t["id"])
        info["waves_total"] = len(by_wave)
        info["waves_done"] = sum(
            1 for ids in by_wave.values() if all(i in done_ids for i in ids))
        nxt = core.next_wave(ledger)
        info["next_wave"] = nxt[0] if nxt else None

    if closed:
        info["state"] = "closed"
    elif ledger_error:
        info["state"] = "unknown (ledger error)"
    elif ledger is not None:
        tasks = ledger.get("tasks", [])
        if tasks and all(t["id"] in done_ids for t in tasks):
            info["state"] = "done"
        elif any(t["id"] in done_ids for t in tasks):
            info["state"] = "in progress"
        else:
            info["state"] = "planned"
    elif (folder / "spec.md").exists():
        info["state"] = "specified"
    return info


def read_backlog(path: Path) -> list:
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return [line[len(OPEN_PREFIX):] for line in text.splitlines()
            if line.startswith(OPEN_PREFIX)]


def _initiatives(root: Path):
    base = Path(root) / "docs" / "initiatives"
    if not base.is_dir():
        return None
    return [initiative_state(p) for p in sorted(base.iterdir()) if p.is_dir()]


def _line(info: dict) -> str:
    parts = [info["state"]]
    if info["waves_total"]:
        parts.append(f"waves {info['waves_done']}/{info['waves_total']}")
    if info["next_wave"] is not None:
        parts.append(f"next wave {info['next_wave']}")
    return f"- {info['name']} ({', '.join(parts)}): {info['path']}"


def _backlog(root: Path) -> list:
    return read_backlog(Path(root) / "docs" / "backlog.md")


def _git(root: Path, *args: str) -> str:
    env = {k: v for k, v in os.environ.items() if k not in ("GIT_DIR", "GIT_WORK_TREE")}
    p = subprocess.run(["git", "-c", "core.quotepath=false", *args], cwd=str(root),
                       capture_output=True, env=env, timeout=10)
    if p.returncode != 0:
        raise RuntimeError("git failed")
    return p.stdout.decode("utf-8", "replace")


def _is_code_file(path: str) -> bool:
    return not (path.startswith(("docs/", ".claude/"))
                or any(part.startswith(".") for part in path.split("/")))


def _codemap_facts(root: Path) -> dict:
    base = Path(root) / ".claude" / "codemap"
    index = _read_text(base / "INDEX.md")
    m = re.search(r"^Generated:\s*(\d{4}-\d{2}-\d{2})", index, re.M)
    pending = {l.strip() for l in _read_text(base / "pending.md").splitlines() if l.strip()}
    return {
        "index": (base / "INDEX.md").is_file(),
        "generated": m.group(1) if m else "",
        "pending": len(pending),
        "symbols": (base / "symbols.md").is_file(),
    }


def _codemap_proposal(root: Path, facts: dict):
    if not facts["index"]:
        files = [p for p in _git(root, "ls-files", "-z").split("\0") if p]
        n = sum(1 for p in files if _is_code_file(p))
        if n >= CODEMAP_MIN_FILES:
            return f"Codemap: none for {n} code files \u2014 propose /codemap (claude-codemap plugin)"
        return None
    if facts["pending"] >= CODEMAP_REBUILD_MIN or not facts["symbols"]:
        return "Codemap: stale \u2014 propose /codemap (full rebuild)"
    if facts["pending"] >= CODEMAP_UPDATE_MIN:
        return f"Codemap: {facts['pending']} pending \u2014 propose /codemap update"
    if facts["generated"]:
        since = datetime.date.fromisoformat(facts["generated"])
        days = (datetime.date.today() - since).days
        if days > CODEMAP_STALE_DAYS:
            commits = int(_git(root, "rev-list", "--count", f"--since={since}T00:00:00",
                               "HEAD").strip())
            if commits >= CODEMAP_STALE_COMMITS:
                return (f"Codemap: {days} days old, {commits} commits since "
                        "\u2014 propose /codemap (full rebuild)")
    return None


def codemap_lines(root: Path) -> list:
    try:
        line = _codemap_proposal(root, _codemap_facts(root))
    except Exception:
        return []
    return [line] if line else []


def _codemap_section(root: Path) -> list:
    facts = _codemap_facts(root)
    try:
        proposal = _codemap_proposal(root, facts)
    except Exception:
        proposal = None
    return [
        "## Codemap",
        f"- Index: {'present' if facts['index'] else 'none'}",
        f"- Generated: {facts['generated'] or 'unknown'}",
        f"- Pending: {facts['pending']}",
        f"- symbols.md: {'present' if facts['symbols'] else 'missing'}",
        f"- Proposed: {proposal[len('Codemap: '):] if proposal else 'up to date'}",
        "",
    ]


def render_full(root: Path) -> str:
    root = Path(root)
    initiatives = _initiatives(root)
    out = ["# Project status", ""]
    if not initiatives:
        out += ["No initiatives yet.", ""]
    else:
        for state, heading in SECTIONS:
            group = [i for i in initiatives if i["state"] == state]
            if group:
                out.append(f"## {heading}")
                out += [_line(i) for i in group]
                out.append("")
        finished = [i for i in initiatives if i["state"] in ("done", "closed")]
        finished.sort(key=lambda i: (i["date"], i["name"]), reverse=True)
        if finished:
            out.append("## Recently done")
            out += [_line(i) for i in finished[:RECENT]]
            out.append("")
    out += _codemap_section(root)
    out.append("## Backlog")
    items = _backlog(root)
    out += [f"- {b}" for b in items] if items else ["No open items."]
    return "\n".join(out) + "\n"


def _status_path(root: Path) -> Path:
    return Path(os.path.abspath(str(Path(root) / "docs" / "STATUS.md")))


def write_status(root: Path) -> Path:
    path = _status_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "\n" + render_full(root))
    return path


def render_brief(root: Path) -> str:
    root = Path(root)
    initiatives = _initiatives(root)
    if initiatives is None:
        return ""
    backlog = _backlog(root)[:BRIEF_BACKLOG]
    tail = []
    if backlog:
        tail.append("Open backlog:")
        tail += [f"- {b}" for b in backlog]
    tail += codemap_lines(root)
    instruction = INSTRUCTION
    status = _status_path(root)
    if status.exists():
        instruction += f" Full status: {status}"
    tail.append(instruction)

    lines = [_line(i) for state in BRIEF_STATES
             for i in initiatives if i["state"] == state]
    budget = BRIEF_MAX_LINES - 1 - len(tail)
    if len(lines) > budget:
        kept = max(budget - 1, 0)
        lines = lines[:kept] + [f"... and {len(lines) - kept} more (see full status)"][:budget]
    head = [f"tech-lead status for {os.path.abspath(str(root))}"]
    return "\n".join(head + lines + tail) + "\n"


def _utf8_streams() -> None:
    for s in (sys.stdout, sys.stderr):
        try:
            s.reconfigure(encoding="utf-8")
        except Exception:
            pass


def _error(msg: str) -> int:
    print(f"error: {msg}", file=sys.stderr)
    return 1


def main(argv: list) -> int:
    _utf8_streams()
    flags = [a for a in argv if a.startswith("--")]
    positional = [a for a in argv if not a.startswith("--")]
    brief = "--brief" in flags
    try:
        if brief and os.environ.get("TECH_LEAD_STATUS") == "0":
            return 0
        unknown = [f for f in flags if f not in ("--brief", "--write")]
        if unknown:
            return _error(f"unknown option {unknown[0]}") if not brief else 0
        if len(positional) > 1 or (brief and "--write" in flags):
            return _error("usage: status.py [ROOT] [--brief | --write]") if not brief else 0
        root = Path(positional[0] if positional
                    else os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd())
        root = Path(os.path.abspath(str(root)))
        if brief:
            text = render_brief(root)
            if text:
                sys.stdout.write(text)
            return 0
        if "--write" in flags:
            print(f"Wrote {write_status(root)}")
            return 0
        sys.stdout.write(render_full(root))
        return 0
    except Exception as e:
        if brief:
            return 0
        return _error(str(e))


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
